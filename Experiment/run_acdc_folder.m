function run_acdc_folder(request_file)
%RUN_ACDC_FOLDER Small bridge from the folder CLI to the existing optimizer.
% No hardware access: this function only prepares and saves numerical results.
root = fileparts(mfilename('fullpath'));
addpath(root);
request = load(request_file);
target_mse = [];
if isfield(request, 'target_mse'), target_mse = request.target_mse; end
[~, summary] = run_experiment_fast_parallel( ...
    request.calibration_file, request.max_current_A, request.workers, ...
    'InputFile', request.input_file, 'OutputDir', request.output_dir, ...
    'FieldLimits', request.field_limit_Hz, ...
    'TotalCurrentLimit_A', request.total_current_limit_A, ...
    'MaxIterations', request.max_iterations, ...
    'TargetMSE', target_mse, ...
    'ThreadsPerWorker', request.threads_per_worker, ...
    'Device', request.device, 'ScratchDir', request.scratch_dir, ...
    'CalibrationMode', 'registered', 'MakeFigures', false);
if ~summary.all_accepted || ~summary.all_current_limits_met || ~summary.all_field_limits_met
    error('run_acdc_folder:NotAccepted', ...
        'Solution saved for inspection, but no feasible convergence or MSE target stop. CSV export is blocked.');
end
end
